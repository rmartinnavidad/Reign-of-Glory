def drive_bones(state, west, south, displacement):
    """Slide the existing SW deform bones along the two-curve cable path.

    Bone.098 and Bone.170 are terminal bones, not full rope spans. The
    West/South mesh seam is at the heads of Bone.098 and Bone.160; mapping
    one terminal tail to the next root splits the original mesh.
    """
    blend = smoothstep(displacement/0.6)
    rig = state["rig"]
    for name in ("Bone.098", "Bone.170"):
        constraint = next(c for c in rig.pose.bones[name].constraints
                          if c.type == "SPLINE_IK")
        # Release only the South and West chains for the v048 cable driver.
        # v047 left the North chain's Spline IK active, so its driven
        # CTRL_Rope Point_TR_N_mid continues to deform that rope normally.
        constraint.influence = 1.0-blend
    if blend <= 0.0:
        saved=json.loads(str(rig[BONE_BACKUP_KEY]))
        for name,values in saved["bones"].items():
            rig.pose.bones[name].matrix_basis=Matrix(
                [values[i:i+4] for i in range(0,16,4)])
        return
    spans = {'W': west, 'S': south}
    span_distances = {}
    for side, points in spans.items():
        distances = [0.0]
        for a,b in zip(points,points[1:]):
            distances.append(distances[-1]+(b-a).length)
        span_distances[side] = distances
    world_to_arm = rig.matrix_world.inverted()
    chains = {'W':[f"Bone.{n:03d}" for n in range(88,98)],
              'S':[f"Bone.{n:03d}" for n in range(160,170)]}
    material = chains['W']+chains['S']
    lengths = {name:(rig.matrix_world.to_3x3() @
                     (rig.data.bones[name].tail_local-
                      rig.data.bones[name].head_local)).length
               for name in material}
    span_material = {side:sum(lengths[name] for name in names)
                     for side,names in chains.items()}
    def at(side, fraction):
        points = spans[side]
        distances = span_distances[side]
        target = max(0.0,min(1.0,fraction))*distances[-1]
        for i in range(len(points)-1):
            if target <= distances[i+1] or i == len(points)-2:
                segment = distances[i+1]-distances[i]
                local = (target-distances[i])/segment if segment > 1e-9 else 0.0
                return points[i].lerp(points[i+1],local)
    desired_matrices = {}
    for side in 'WS':
      distance_on_material = 0.0
      for name in chains[side]:
        pose = rig.pose.bones[name]
        bone = rig.data.bones[name]
        first = at(side,distance_on_material/span_material[side])
        last = at(side,(distance_on_material+lengths[name])/span_material[side])
        direction = last-first
        if direction.length < 1e-7:
            direction = spans[side][-1]-spans[side][0]
        direction_local = (world_to_arm.to_3x3() @ direction).normalized()
        rest_direction = bone.tail_local-bone.head_local
        rotation = (rest_direction.rotation_difference(direction_local) @
                    bone.matrix_local.to_quaternion())
        head = world_to_arm @ first
        scale_y = (world_to_arm.to_3x3() @ direction).length/bone.length
        desired = Matrix.LocRotScale(head,rotation,Vector((1.0,scale_y,1.0)))
        if pose.parent is None:
            pose.matrix_basis = bone.convert_local_to_pose(
                desired,bone.matrix_local,invert=True)
        else:
            parent_matrix = desired_matrices.get(pose.parent.name,pose.parent.matrix)
            pose.matrix_basis = bone.convert_local_to_pose(
                desired,bone.matrix_local,parent_matrix=parent_matrix,
                parent_matrix_local=pose.parent.bone.matrix_local,invert=True)
        desired_matrices[name] = desired
        distance_on_material += lengths[name]
    # The two terminal bones carry endpoint vertex weights but do not add a
    # further rope span. Align each head to the neighbouring material joint.
    for name,source in (("Bone.098","Bone.097"),("Bone.170","Bone.169")):
        pose = rig.pose.bones[name]
        bone = rig.data.bones[name]
        neighbour = desired_matrices[source]
        joint = neighbour @ Vector((0.0,rig.data.bones[source].length,0.0))
        deformation_rotation = (neighbour.to_quaternion() @
                                rig.data.bones[source].matrix_local.to_quaternion().inverted())
        terminal_rotation = deformation_rotation @ bone.matrix_local.to_quaternion()
        desired = Matrix.LocRotScale(joint,terminal_rotation,
                                     Vector((1.0,1.0,1.0)))
        parent = pose.parent
        parent_matrix = desired_matrices.get(parent.name,parent.matrix)
        pose.matrix_basis = bone.convert_local_to_pose(
            desired,bone.matrix_local,parent_matrix=parent_matrix,
            parent_matrix_local=parent.bone.matrix_local,invert=True)
        desired_matrices[name] = desired


