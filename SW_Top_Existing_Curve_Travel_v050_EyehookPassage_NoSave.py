def sw_material_length():
    """Measure actual authored rope-bone material, not only control chords."""
    rig = bpy.data.objects.get("BONES_ROPES")
    if rig is None or rig.type != "ARMATURE":
        raise RuntimeError("Original BONES_ROPES armature is missing")
    totals = {}
    for side, tip_name in (("W", "Bone.098"), ("S", "Bone.170")):
        bone = rig.data.bones.get(tip_name)
        if bone is None:
            raise RuntimeError(f"Original top-rope tip {tip_name} is missing")
        total = 0.0
        for _ in range(11):
            if bone is None:
                raise RuntimeError(f"The {side} top-rope bone chain is incomplete")
            total += (rig.matrix_world.to_3x3() @ (bone.tail_local-bone.head_local)).length
            bone = bone.parent
        totals[side] = total
    return totals


