    groups = {name:mesh.vertex_groups.get(name) for name in names}
    if any(group is None for group in groups.values()):
        raise RuntimeError("An original SW top bone vertex group is missing")
    group_index = {group.index:name for name,group in groups.items()}
    lengths = {name:rig.data.bones[name].length for name in material}
    starts,centres = {},{}
    distance = 0.0
    for name in material:
        starts[name] = distance
        centres[name] = distance+lengths[name]*0.5
        distance += lengths[name]
    mesh_to_arm = rig.matrix_world.inverted() @ mesh.matrix_world
    backup = {}
    replacements = {}
    for vertex in mesh.data.vertices:
        sw = [(group_index[g.group],float(g.weight)) for g in vertex.groups
              if g.group in group_index and g.weight > 0.0]
        if not sw:
            continue
        total_weight = sum(weight for _,weight in sw)
        if total_weight < 0.4:
            continue
        arm_co = mesh_to_arm @ vertex.co
        arc = 0.0
        for name,weight in sw:
            if name in starts:
                bone = rig.data.bones[name]
                direction = bone.tail_local-bone.head_local
                fraction = max(0.0,min(1.0,(arm_co-bone.head_local).dot(direction)/
                                       direction.length_squared))
                coordinate = starts[name]+lengths[name]*fraction
            else:
                coordinate = distance if name == "Bone.170" else starts["Bone.160"]
            arc += coordinate*weight/total_weight
        factors = {name:max(0.0,1.0-abs(arc-centre)/0.72)**2
                   for name,centre in centres.items()}
        factor_sum = sum(factors.values())
        if factor_sum < 1e-9:
            continue
        backup[vertex.index] = sw
        replacements[vertex.index] = {
            name:total_weight*factor/factor_sum for name,factor in factors.items()
            if factor > 1e-7}
    encoded = base64.b64encode(zlib.compress(json.dumps(backup).encode("utf-8"))).decode("ascii")
    mesh[WEIGHT_BACKUP_KEY] = encoded
    for name,group in groups.items():
        indices = [index for index,weights in backup.items()
                   if any(weight_name == name for weight_name,_ in weights)]
        if indices:
            group.remove(indices)
    for index,weights in replacements.items():
        for name,weight in weights.items():
            groups[name].add([index],weight,"REPLACE")
    return len(replacements)


